#!/usr/bin/env python3
"""Generate firmware/components/pocket_ui/src/font_ui.inc — Pocket's 1-bit UI type.

The Waveshare 3.97" panel is driven monochrome (epd.cpp thresholds every frame
to 1 bit), so glyphs are stored as 1bpp with a tight ink box, real advances and
a per-face line box. Anti-aliased 2bpp fonts just broke up on device.

Each face is rasterized at 4x, box-filtered down and thresholded at a per-face
coverage cut — a hair heavier than 50% so thin serifs and DM Sans hairlines
survive the 1-bit panel without going blobby.

Faces match the Companion brand: DM Sans (UI) + Source Serif 4 (display).
Fonts live in tools/fonts/ (SIL OFL 1.1).

    python3 tools/gen_fonts.py            # writes components/pocket_ui/src/font_ui.inc
    python3 tools/gen_fonts.py --preview out.png
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
FONTS = HERE / "fonts"
OUT = HERE.parent / "components/pocket_ui/src/font_ui.inc"

ASCII = [chr(c) for c in range(32, 127)]
LATIN1 = [chr(c) for c in range(0xA0, 0x100)]
PUNCT = list("–—‘’“”•…←→↑↓‹›")
FULL = ASCII + LATIN1 + PUNCT


@dataclass
class Face:
    name: str
    ttf: str
    px: int
    line_h: int
    cut: float  # coverage threshold 0..1 (lower = bolder)
    chars: list[str]
    track: int = 0  # extra advance px


FACES = [
    Face("Caption", "DMSans-Medium.ttf", 19, 26, 0.40, FULL, 1),
    Face("Secondary", "DMSans-Regular.ttf", 23, 30, 0.40, FULL),
    Face("Status", "DMSans-SemiBold.ttf", 21, 30, 0.45, ASCII),
    Face("Body", "DMSans-Regular.ttf", 27, 33, 0.36, FULL),
    Face("BodyStrong", "DMSans-SemiBold.ttf", 27, 33, 0.45, FULL),
    Face("Title", "SourceSerif4-SemiBold.ttf", 40, 49, 0.45, FULL),
    Face("Reading", "SourceSerif4-Regular.ttf", 24, 34, 0.40, FULL),
    Face("Pin", "SourceSerif4Display-Medium.ttf", 48, 64, 0.45, list("0123456789• ")),
    Face("Hero", "SourceSerif4Display-Regular.ttf", 92, 100, 0.45,
         list("0123456789:°-–. %ACFMP")),
    Face("Huge", "SourceSerif4Display-Regular.ttf", 170, 147, 0.45, list("0123456789: ")),
]

SS = 4


def rasterize(face: Face):
    font = ImageFont.truetype(str(FONTS / face.ttf), face.px * SS)
    cap_top = font.getbbox("H", anchor="ls")[1] / SS  # negative: cap height above baseline
    cap_h = -cap_top
    # Optically center the cap height in the line box.
    baseline = int(round((face.line_h + cap_h) / 2))
    glyphs = []
    for ch in face.chars:
        adv = int(round(font.getlength(ch) / SS)) + face.track
        l, t, r, b = font.getbbox(ch, anchor="ls")
        if r <= l or b <= t or ch == " ":
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, b""))
            continue
        # Align the 4x canvas to the 1x pixel grid.
        ox = (l // SS) * SS
        oy = (t // SS) * SS
        W = ((r - ox) + SS - 1) // SS
        H = ((b - oy) + SS - 1) // SS
        img = Image.new("L", (W * SS, H * SS), 0)
        ImageDraw.Draw(img).text((-ox, -oy), ch, font=font, fill=255, anchor="ls")
        small = img.resize((W, H), Image.BOX)
        px = small.load()
        rows = []
        thr = int(face.cut * 255)
        for y in range(H):
            rows.append([1 if px[x, y] >= thr else 0 for x in range(W)])
        # Trim empty rows/cols.
        ys = [y for y in range(H) if any(rows[y])]
        xs = [x for x in range(W) if any(rows[y][x] for y in range(H))]
        if not ys:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, b""))
            continue
        y0, y1, x0, x1 = ys[0], ys[-1], xs[0], xs[-1]
        w, h = x1 - x0 + 1, y1 - y0 + 1
        data = bytearray()
        for y in range(y0, y1 + 1):
            byte = 0
            nb = 0
            for x in range(x0, x1 + 1):
                byte = (byte << 1) | rows[y][x]
                nb += 1
                if nb == 8:
                    data.append(byte)
                    byte = nb = 0
            if nb:
                data.append(byte << (8 - nb))
        xoff = ox // SS + x0
        yoff = baseline + oy // SS + y0  # top of ink relative to line-box top
        glyphs.append((ord(ch), w, h, xoff, yoff, adv, bytes(data)))
    glyphs.sort(key=lambda g: g[0])
    return glyphs


def emit(faces_glyphs, out: Path):
    total = 0
    with out.open("w") as f:
        f.write("// Generated by tools/gen_fonts.py — do not edit.\n")
        f.write("// 1bpp glyphs, tight ink box, MSB-first rows padded to bytes.\n")
        f.write("// DM Sans + Source Serif 4 (SIL Open Font License 1.1).\n\n")
        f.write("struct FontGlyph { uint16_t cp; uint8_t w, h; int8_t xoff; int8_t yoff; uint8_t adv; uint32_t off; };\n")
        f.write("struct FontFace { const FontGlyph* glyphs; uint16_t count; uint8_t line_h; const uint8_t* bits; };\n\n")
        for face, glyphs in faces_glyphs:
            blob = bytearray()
            entries = []
            for cp, w, h, xoff, yoff, adv, data in glyphs:
                entries.append((cp, w, h, xoff, yoff, adv, len(blob)))
                blob += data
            total += len(blob) + 12 * len(entries)
            n = face.name
            f.write(f"// {n}: {face.ttf} {face.px}px, line {face.line_h}, {len(entries)} glyphs, {len(blob)} B\n")
            f.write(f"static const uint8_t kFont{n}Bits[] = {{")
            for i, b in enumerate(blob):
                if i % 24 == 0:
                    f.write("\n  ")
                f.write(f"{b},")
            f.write("\n};\n")
            f.write(f"static const FontGlyph kFont{n}Glyphs[] = {{\n")
            for cp, w, h, xoff, yoff, adv, off in entries:
                f.write(f"  {{{cp}, {w}, {h}, {xoff}, {yoff}, {adv}, {off}}},\n")
            f.write("};\n")
            f.write(f"static const FontFace kFont{n} = {{kFont{n}Glyphs, {len(entries)}, {face.line_h}, kFont{n}Bits}};\n\n")
    return total


def preview(faces_glyphs, path: str):
    rows = []
    for face, glyphs in faces_glyphs:
        sample = "".join(chr(g[0]) for g in glyphs)[:60] if len(glyphs) < 40 else \
            "Pocket — Notes, Lists & Café · 9:41 AM 78% Gymnopédie"
        by = {g[0]: g for g in glyphs}
        W = 1400
        img = Image.new("L", (W, face.line_h), 255)
        x = 4
        for ch in sample:
            g = by.get(ord(ch))
            if not g:
                continue
            cp, w, h, xoff, yoff, adv, data = g
            rb = (w + 7) // 8
            for yy in range(h):
                for xx in range(w):
                    if data[yy * rb + xx // 8] & (0x80 >> (xx % 8)):
                        if 0 <= x + xoff + xx < W:
                            img.putpixel((x + xoff + xx, yoff + yy), 0)
            x += adv
        rows.append(img)
    H = sum(r.height + 6 for r in rows)
    sheet = Image.new("L", (1400, H), 255)
    y = 0
    for r in rows:
        sheet.paste(r, (0, y))
        y += r.height + 6
    sheet.save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--preview")
    a = ap.parse_args()
    fg = [(face, rasterize(face)) for face in FACES]
    if a.preview:
        preview(fg, a.preview)
        print("preview", a.preview)
        return
    total = emit(fg, a.out)
    print(f"wrote {a.out} (~{total} bytes of font data)")


if __name__ == "__main__":
    main()
