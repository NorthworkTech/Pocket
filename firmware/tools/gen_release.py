#!/usr/bin/env python3
"""release.json → components/pocket_ui/include/pocket/release.hpp.

release.json is the single source for the OS name, version and release notes:
- the device embeds them (About, the post-update Welcome screen),
- CI copies them into firmware-manifest.json so devices see them before installing.
Run after editing release.json:  python3 tools/gen_release.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rel = json.loads((root / "release.json").read_text())


def c_str(s: str) -> str:
    out = []
    for ch in s.encode("utf-8"):
        if ch in (0x22, 0x5C):
            out.append("\\" + chr(ch))
        elif 0x20 <= ch < 0x7F:
            out.append(chr(ch))
        else:
            out.append("\\x%02X\" \"" % ch)  # split literal so hex escapes never swallow digits
    return '"' + "".join(out) + '"'


notes = rel["notes"]
lines = [
    "#pragma once",
    "// Generated by tools/gen_release.py from firmware/release.json — do not edit.",
    "namespace pocket {",
    f"inline constexpr const char* kOsName = {c_str(rel['os'])};",
    f"inline constexpr const char* kOsVersion = {c_str(rel['version'])};",
    f"inline constexpr const char* kOsDisplayName = {c_str(rel['name'])};",
    f"inline constexpr int kReleaseNoteCount = {len(notes)};",
    "inline constexpr const char* kReleaseNotes[] = {",
    *[f"    {c_str(n)}," for n in notes],
    "};",
    "}  // namespace pocket",
    "",
]
out = root / "components/pocket_ui/include/pocket/release.hpp"
out.write_text("\n".join(lines))
print("wrote", out)
